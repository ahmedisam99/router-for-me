import { useId, useState, type FormEvent } from 'react';
import { useTranslation } from 'react-i18next';
import { Button } from '@/components/ui/Button';
import { Input } from '@/components/ui/Input';
import { Modal } from '@/components/ui/Modal';
import { ApiKeyStrengthMeter } from '@/features/config/components/blocks/ApiKeyStrengthMeter';
import { generateSecureApiKey } from '@/utils/apiKey';
import { isValidApiKeyCharset } from '@/utils/validation';
import styles from '../KeysPage.module.scss';

interface AddKeyModalProps {
  /** Keys already in config, to refuse a duplicate. */
  existing: readonly string[];
  onClose: () => void;
  onSubmit: (key: string, name: string) => Promise<void>;
}

/** A new client key, generated by default, built from the config page's key pieces. */
export function AddKeyModal({ existing, onClose, onSubmit }: AddKeyModalProps) {
  const { t } = useTranslation();
  const formId = useId();
  const keyId = useId();
  const errorId = useId();
  const [name, setName] = useState('');
  const [key, setKey] = useState(generateSecureApiKey);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState('');

  const submit = async (event: FormEvent) => {
    event.preventDefault();
    const trimmed = key.trim();
    const problem = !trimmed
      ? t('config_management.visual.api_keys.error_empty')
      : !isValidApiKeyCharset(trimmed)
        ? t('config_management.visual.api_keys.error_invalid')
        : existing.includes(trimmed)
          ? t('keys_page.key_exists')
          : '';
    setError(problem);
    if (problem) return;
    setSaving(true);
    try {
      await onSubmit(trimmed, name);
      onClose();
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err));
      setSaving(false);
    }
  };

  return (
    <Modal
      open
      onClose={onClose}
      closeDisabled={saving}
      width={520}
      title={t('keys_page.add_key')}
      footer={
        <>
          <Button variant="secondary" onClick={onClose} disabled={saving}>
            {t('common.cancel')}
          </Button>
          <Button type="submit" form={formId} loading={saving}>
            {t('common.add')}
          </Button>
        </>
      }
    >
      <form id={formId} className={styles.form} onSubmit={(event) => void submit(event)}>
        <Input
          label={t('keys_page.name')}
          value={name}
          onChange={(event) => setName(event.target.value)}
          autoFocus
        />
        <div className="form-group">
          <label htmlFor={keyId}>{t('config_management.visual.api_keys.input_label')}</label>
          <div className={styles.keyRow}>
            <input
              id={keyId}
              className="input"
              value={key}
              onChange={(event) => setKey(event.target.value)}
              aria-invalid={Boolean(error)}
              aria-describedby={error ? errorId : undefined}
              autoComplete="off"
              spellCheck={false}
            />
            <Button
              type="button"
              variant="secondary"
              size="sm"
              onClick={() => {
                setKey(generateSecureApiKey());
                setError('');
              }}
            >
              {t('config_management.visual.api_keys.generate')}
            </Button>
          </div>
          <ApiKeyStrengthMeter value={key} />
        </div>
        {error ? (
          <div id={errorId} className="error-box">
            {error}
          </div>
        ) : null}
      </form>
    </Modal>
  );
}
